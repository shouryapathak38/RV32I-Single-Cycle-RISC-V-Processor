module decode_top_tb;

reg         clk;
reg [31:0]  instruction;
reg [31:0]  write_data;
reg [2:0]   Flags;

wire [31:0] rs1_data;
wire [31:0] rs2_data;
wire [31:0] immExt;

wire        RegWrite;
wire [1:0]  ResultSrc;
wire        MemRW;
wire        Jump;
wire        Branch;
wire [1:0]  ALUSrc;
wire [3:0]  ALUControl;
wire        PCSrc;

decode_top dut(
    .clk(clk),
    .instruction(instruction),
    .write_data(write_data),
    .Flags(Flags),

    .rs1_data(rs1_data),
    .rs2_data(rs2_data),
    .immExt(immExt),

    .RegWrite(RegWrite),
    .ResultSrc(ResultSrc),
    .MemRW(MemRW),
    .Jump(Jump),
    .Branch(Branch),
    .ALUSrc(ALUSrc),
    .ALUControl(ALUControl),
    .PCSrc(PCSrc)
);

always #5 clk = ~clk;

initial begin

    clk = 0;
    write_data = 32'd0;
    Flags = 3'b000;

    //--------------------------------------------------
    // R-Type ADD
    //--------------------------------------------------
    instruction = 32'b0000000_00011_00010_000_00001_0110011;
    #10;

    //--------------------------------------------------
    // SUB
    //--------------------------------------------------
    instruction = 32'b0100000_00011_00010_000_00001_0110011;
    #10;

    //--------------------------------------------------
    // ADDI
    //--------------------------------------------------
    instruction = 32'b000000001010_00010_000_00001_0010011;
    #10;

    //--------------------------------------------------
    // SLTI
    //--------------------------------------------------
    instruction = 32'b000000000101_00010_010_00001_0010011;
    #10;

    //--------------------------------------------------
    // LW
    //--------------------------------------------------
    instruction = 32'b000000001000_00010_010_00001_0000011;
    #10;

    //--------------------------------------------------
    // SW
    //--------------------------------------------------
    instruction = 32'b0000000_00001_00010_010_01000_0100011;
    #10;

    //--------------------------------------------------
    // BEQ (Not Taken)
    //--------------------------------------------------
    Flags = 3'b000;

    instruction = 32'b0000000_00011_00010_000_00000_1100011;
    #10;

    //--------------------------------------------------
    // BEQ (Taken)
    //--------------------------------------------------
    Flags = 3'b100;
    #10;

    //--------------------------------------------------
    // BNE
    //--------------------------------------------------
    Flags = 3'b000;

    instruction = 32'b0000000_00011_00010_001_00000_1100011;
    #10;

    //--------------------------------------------------
    // BLT
    //--------------------------------------------------
    Flags = 3'b010;

    instruction = 32'b0000000_00011_00010_100_00000_1100011;
    #10;

    //--------------------------------------------------
    // BGE
    //--------------------------------------------------
    Flags = 3'b000;

    instruction = 32'b0000000_00011_00010_101_00000_1100011;
    #10;

    //--------------------------------------------------
    // BLTU
    //--------------------------------------------------
    Flags = 3'b001;

    instruction = 32'b0000000_00011_00010_110_00000_1100011;
    #10;

    //--------------------------------------------------
    // BGEU
    //--------------------------------------------------
    Flags = 3'b000;

    instruction = 32'b0000000_00011_00010_111_00000_1100011;
    #10;

    //--------------------------------------------------
    // JAL
    //--------------------------------------------------
    instruction = 32'h000000EF;
    #10;

    //--------------------------------------------------
    // JALR
    //--------------------------------------------------
    instruction = 32'h00008067;
    #10;

    //--------------------------------------------------
    // LUI
    //--------------------------------------------------
    instruction = 32'h123450B7;
    #10;

    //--------------------------------------------------
    // AUIPC
    //--------------------------------------------------
    instruction = 32'h12345117;
    #10;

    $stop;

end

endmodule